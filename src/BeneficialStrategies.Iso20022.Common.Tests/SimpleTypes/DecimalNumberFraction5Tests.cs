namespace BeneficialStrategies.Iso20022.SimpleTypes;

[Obsolete("The type being tested is obsolete in the ISO 20022 specification.")]
public class DecimalNumberFraction5Tests : SimpleValueXsdNumericContractTests<DecimalNumberFraction5, decimal>
{
    protected override decimal ValidNativeSample => 12345.5m;

    [Fact]
    public void ExcessiveTotalDigits_ThrowsFormatException()
    {
        Assert.Throws<Iso20022FormatException>(() => new DecimalNumberFraction5(1000000000000000000m));
    }

    [Fact]
    public void ExcessiveFractionDigits_ThrowsFormatException()
    {
        Assert.Throws<Iso20022FormatException>(() => new DecimalNumberFraction5(1.123456m));
    }
}
